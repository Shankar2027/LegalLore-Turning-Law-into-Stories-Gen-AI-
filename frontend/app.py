"""LegalLore - Streamlit UI."""
import streamlit as st
import requests  
import base64    

import api_client as api
import ui_components as ui

st.set_page_config(page_title="LegalLore", page_icon="⚖️", layout="wide")
ui.inject_css()

# ==========================================
# Main Header
# ==========================================
st.title("⚖️ LegalLore")
st.caption("Learn how the law works through stories.")

# ==========================================
# Sidebar: Player Profile
# ==========================================
with st.sidebar:
    st.markdown("### 👤 Player Profile")
    username = st.text_input("Enter Username:", value="guest", help="Type any name to start saving your progress!")
    user_data = api.get_user(username)
    st.write(f"**Score:** {user_data['quiz_score']} 🏆")
    if user_data['badges']:
        st.write(f"**Badges:** {', '.join(user_data['badges'])} 🏅")
    st.divider()

@st.cache_data(ttl=600, show_spinner=False)
def load_terms():
    return api.get_terms()

try:
    terms = load_terms()
except api.APIError as e:
    st.error(str(e))
    st.stop()

# Sidebar: Core Story Inputs
form = ui.sidebar_inputs(terms)

# ==========================================
# Sidebar: Condensed Advanced Options
# ==========================================
with st.sidebar:
    with st.expander("📄 Upload Legal Documents", expanded=False):
        uploaded_files = st.file_uploader(
            "Upload documents to include in your story!", 
            accept_multiple_files=True # Removed 'type' restriction to accept ALL file formats
        )
    
    with st.expander("🌍 Advanced Settings", expanded=False):
        language = st.selectbox("Story Language", ["English", "Kannada", "Telugu", "Hindi"])
        case_law_mode = st.toggle("🏛️ Real Case Law Mode", value=False)
        
        # Auto-level quiz based on the user's DB score
        quiz_difficulty = st.selectbox("Quiz Difficulty", ["Beginner", "Advanced"], index=1 if user_data['quiz_score'] >= 3 else 0)

if form["go"]:
    with st.spinner("The Architect is writing, drawing, and recording…"):
        try:
            st.session_state.pop("result", None)
            st.session_state.pop("messages", None) 
            for k in [k for k in st.session_state if k.startswith("q")]:
                del st.session_state[k]

            # Send ALL files to FastAPI for extraction dynamically
            pdf_context = None
            if uploaded_files:
                # Updated to send f.type instead of hardcoding "application/pdf"
                files_payload = [("files", (f.name, f.getvalue(), f.type)) for f in uploaded_files]
                pdf_context = api.upload_pdfs(files_payload)
                
            st.session_state["result"] = api.generate_story(
                form["terms"], form["word_count"], form["genre"], form["age_group"], 
                form["include_quiz"], language=language, quiz_difficulty=quiz_difficulty,
                case_law_mode=case_law_mode, pdf_context=pdf_context, username=username
            )
        except api.APIError as e:
            st.error(f"Could not create the story. {e}")

res = st.session_state.get("result")

if res:
    # ==========================================
    # Unified Story Card Container
    # ==========================================
    with st.container(border=True):
        if res.get("image_url"):
            st.image(res["image_url"], use_container_width=True, caption="Generated by LegalLore Art Director")
            
        if res.get("audio_base64"):
            try:
                audio_bytes = base64.b64decode(res["audio_base64"])
                st.audio(audio_bytes, format="audio/mp3")
                st.divider()
            except Exception as e:
                st.error(f"Could not load audio player: {e}")

        ui.story_view(res)

    ui.glossary_view(res["definitions"])
    ui.critic_view(res["critic"], res["revisions_used"])
    
    # ==========================================
    # Interactive Quiz Scoring UI
    # ==========================================
    if res.get("quiz"):
        st.markdown("### 🧠 Test yourself")
        
        # Wrapping in st.form prevents the page from blinking when selecting answers
        with st.form("quiz_form"):
            user_answers = {}
            for i, q in enumerate(res["quiz"]["questions"]):
                # Record the user's selected answer for each question
                user_answers[i] = st.radio(q["question"], q["options"], key=f"q_{i}", index=None)
            
            # One single submit button for the whole quiz
            submitted = st.form_submit_button("Submit Answers & Claim Points!")
            
            if submitted:
                score_this_round = 0
                
                # Check all answers at once
                for i, q in enumerate(res["quiz"]["questions"]):
                    correct_option = q["options"][q["answer_index"]]
                    
                    if user_answers[i] == correct_option:
                        st.success(f"Question {i+1}: Correct! +1 Point 🏆")
                        score_this_round += 1
                    elif user_answers[i] is None:
                        st.warning(f"Question {i+1}: You forgot to answer this one!")
                    else:
                        st.error(f"Question {i+1}: Incorrect. The correct answer was: {correct_option}")
                
                # If they got at least 1 point, trigger balloons and update DB
                if score_this_round > 0:
                    st.balloons()  
                    
                    updated_user = api.update_score(username, score_this_round) 
                    
                    st.success(f"🎉 Points claimed! New Total: {updated_user['quiz_score']}")
                    
                    if updated_user.get("new_badges_awarded"):
                        st.success(f"🏅 New Badge Unlocked: {', '.join(updated_user['new_badges_awarded'])}!")

    # ==========================================
    # Cross-Examine Chat (Un-pinned Expander)
    # ==========================================
    st.divider()
    with st.expander("💬 Cross-Examine the Character!", expanded=False):
        if "messages" not in st.session_state:
            st.session_state.messages = []

        for msg in st.session_state.messages:
            with st.chat_message(msg["role"]):
                st.write(msg["content"])

        with st.form("chat_form", clear_on_submit=True):
            cols = st.columns([5, 1])
            prompt = cols[0].text_input("Ask a question about the story...", label_visibility="collapsed")
            chat_submitted = cols[1].form_submit_button("Send")

            if chat_submitted and prompt:
                st.chat_message("user").write(prompt)
                st.session_state.messages.append({"role": "user", "content": prompt})

                chat_payload = {
                    "story_context": res.get("story", ""), 
                    "legal_terms": form["terms"],
                    "user_message": prompt
                }
                
                with st.spinner("The character is thinking..."):
                    try:
                        response = requests.post("http://127.0.0.1:8000/chat", json=chat_payload)
                        response.raise_for_status()
                        reply = response.json()["reply"]
                        st.chat_message("assistant").write(reply)
                        st.session_state.messages.append({"role": "assistant", "content": reply})
                    except Exception as e:
                        st.error(f"Chat connection error. Details: {e}")

else:
    st.info("👈 Pick 3 legal terms, a genre and a length, then press **Create story**.")